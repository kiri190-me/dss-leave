/**
 * 이 시스템이 굽는 쿠키의 이름. **전부 여기 모아 둔다.**
 *
 * ── 🔴 왜 한 파일에 모으는가 ────────────────────────────────────────────
 * **쿠키는 포트를 가리지 않는다.** localhost:3700(휴가 관리)과
 * localhost:3000(A/S)은 브라우저에게 **같은 사이트**라 **같은 쿠키 통**을 쓴다.
 * 이름이 겹치면 한쪽에 로그인하는 순간 다른 쪽 로그인이 조용히 덮어써진다 —
 * A/S 에서 실제로 났던 구멍이고, 증상이 "가끔 로그아웃된다" 라서 찾기 어렵다.
 *
 * 그래서 이 시스템의 몫은 전부 `leave_` 로 시작한다. 이름이 세 파일에 흩어져
 * 있으면 네 번째를 더하는 사람이 그 규칙을 못 보고 지나간다. 여기 모여 있으면
 * 새 이름을 적는 자리에서 규칙이 눈에 들어온다.
 *
 * 사내 다른 시스템의 몫: 포털 `dss_sso` · A/S `as_*` · 계측기 `meters_*` ·
 * 개선요청 `improvements_*` · PO/내자 `po_*`.
 *
 * 이 파일에는 import 가 하나도 없다 — DB 에도 next/headers 에도 닿지 않아야
 * `npm run test:auth` 가 이름 규칙을 검사할 수 있다.
 */

