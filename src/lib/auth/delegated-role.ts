/**
 * ============================================================================
 * 결재권 위임이 **역할까지 넘긴다** — 순수 규칙 (2026-11-17)
 * ============================================================================
 * 사용자 결정: **`LEAVE_ADMIN` 이 맡긴 위임의 대리인은 그 기간 동안
 * `LEAVE_ADMIN` 이다.** 🔴 다만 **「역할 변경」만은 주지 않는다**(아래
 * `mayChangeUserRole`). 새 기능을 만든 것이 아니라 **이미 있는 위임 한 줄에 뜻을
 * 더한** 것이다 — 지정하는 화면도, 거두는 화면도, 표도 그대로다.
 *
 * ── 🔴 「관리자를 준다」는 「결재권을 준다」가 아니다 ──────────────────────
 * 이 집의 승인·반려 판정은 **결재선에 이름이 있는가**로만 갈린다
 * (leave/approval-scope.ts 의 `isMyStep`·`myStepCondition` — 그 파일에는
 * `LEAVE_ADMIN` 도 `isAdmin` 도 한 글자가 없다). 직급에 결재권이 없어도 결재선에
 * 있으면 누르고, 휴가 관리자여도 결재선에 없으면 못 누른다.
 * 🔴 **그러니 이 파일은 결재 판정을 한 글자도 건드리지 않는다.** 여기서 정해지는
 * 것은 **「관리자 역할이 여는 다른 문들」**(직원 명단 · 연차 직접 조정 · 근속 표 ·
 * 공휴일 · 전사 여름휴가 일수 · 결재선 구성 …)이다.
 * 🔴 역할을 결재 판정에 끼워 넣지 마라. 끼우는 순간 「결재선에 없는데 누를 수 있는
 * 사람」이 생기고, 그 건은 나중에 「왜 저 사람이 눌렀나」에 답할 자리가 없다.
 *
 * ── 🔴 **DB 의 역할 칸(`web_users.role`)을 쓰지 않는다** ──────────────────
 * 이 집은 역할을 **매 요청마다 DB 에서 다시 읽는다**(auth/session.ts 의
 * `getSessionUser` → auth/guards.ts 의 `getViewer`). 그래서 「**지금** 유효한
 * 위임의 위임자 중 `LEAVE_ADMIN` 이 있나」를 **판정 시점에 계산**하면 된다 —
 * 기간이 끝나면 다음 요청부터 **저절로** 닫히고, 밤에 도는 작업표도 만료 처리도
 * 필요 없다. 위임이 열리는 조건과 닫히는 조건이 **같은 자리 하나**라는 것이 이
 * 설계의 안전장치다(auth/portal-delegations.ts 의 `liveDelegationWhere` 머리말).
 * 🔴 `web_users.role` 을 **바꿔 적는** 길로 가지 마라. 그 순간 여는 조건(위임 줄)과
 * 닫는 조건(사람의 손)이 다른 곳에 생기고, **화면에서 내릴 수 없는 권한**이 남는다.
 *
 * ── 🔴 `user.role` 자체는 **승격하지 않는다** — 재고관리와 다른 점 ────────
 * 재고관리의 같은 기능은 세션이 들고 다니는 `user.role` 을 `ADMIN` 으로 갈아
 * 끼웠다. 이 집에서는 그러지 않는다:
 *  · 이 집의 문은 **전부** `viewer.isAdmin` 하나를 묻는다(guards.ts 의
 *    `requireAdmin` · workflow.ts 의 두 자리 · 화면들). `user.role` 을 직접 묻는
 *    **울타리는 한 곳도 없다** — 그 값을 읽는 자리는 「남의 계정 줄을 화면에
 *    그린다」와 **감사 로그 요약문**뿐이다.
 *  · 🔴 감사 로그(`writeAudit`)는 `admin.user` 를 그대로 받는다. 거기에 승격된
 *    역할을 실으면 **기록이 거짓말을 한다** — 「그 사람은 그때 관리자였다」로 남고,
 *    위임 줄과 맞대어 보기 전까지 아무도 모른다.
 * 🔵 그래서 **승격은 `isAdmin` 한 칸에서만** 일어난다. 어느 날 누가 `user.role` 로
 *    새 울타리를 적어도 그쪽은 **좁게**(임시 관리자가 거절) 틀릴 뿐이라, 틀리는
 *    방향이 안전한 쪽이다.
 *
 * ── 🔵 왜 순수 모듈인가 ────────────────────────────────────────────────
 * 표를 읽는 층(auth/portal-delegations.ts)도 세션 층(auth/guards.ts)도 DB·
 * next/navigation 을 끌고 와 **시험이 불러올 수 없다.** 그래서 뜻은 여기 두고
 * 저쪽은 「읽어다 넘기는 일」만 한다 — auth/sso-role.ts ·
 * leave/approval-scope.ts 와 같은 자리, 같은 까닭이다.
 * ============================================================================
 */
import type { UserRole } from "@/lib/db/schema";

/**
 * 🔴 **이 역할의 위임자만 역할을 넘긴다.** `MEMBER` 가 맡긴 위임은 **결재권만**
 * 넘어가고 역할은 그대로다 — 넘길 것이 없기 때문이다.
 *
 * 🔵 글자를 여기 한 번만 적는 까닭은 `settings-tabs.ts`·`sso-role.ts` 와 같다:
 *    시험이 「무엇이 기준인가」를 **이 이름으로** 물을 수 있어야 한다.
 */
export const DELEGATED_ADMIN_SOURCE_ROLE: UserRole = "LEAVE_ADMIN";

/**
 * 이번 요청에서 **관리자인가**, 그리고 그것이 **위임에서 온 것인가**.
 *
 * 🔴 두 칸을 **함께** 들고 다닌다. `isAdmin` 만 들고 다니면 아래 `mayChangeUserRole`
 * 을 걸 자리가 사라지고(임시인지 알 길이 없다), 깃발만 들고 다니면 문을 묻는
 * 자리마다 승격을 다시 적어야 한다.
 */
export type DelegatedAdminDecision = {
  /** 🔴 **이번 요청에서 관리자 문이 열리는가.** 진짜 관리자이거나, 위임으로 받았거나. */
  isAdmin: boolean;
  /**
   * 🔴 **그 관리자 자격이 결재권 위임에서 왔는가.** 진짜 `LEAVE_ADMIN` 은 위임을
   * 받았든 안 받았든 **언제나 `false`** 다 — 이 깃발은 「권한이 있나」가 아니라
   * **「역할 변경까지 되나」**를 가르는 값이다.
   */
  delegatedAdmin: boolean;
};

/**
 * 「지금 이 사람이 관리자인가 · 그것이 임시인가」를 가르는 **유일한 자리**.
 *
 * @param ownRole DB 가 준 진짜 역할(`web_users.role` 의 지금 값).
 * @param delegatorRoles 지금 **내가 대신하는 사람들**의 역할.
 *   🔴 「지금 유효한가」(기간·철회)는 **여기서 재지 않는다** — 넘겨받는 목록이
 *   이미 걸러진 것이어야 한다(auth/portal-delegations.ts 의 `liveDelegationWhere`
 *   한 곳이 그 일을 한다). 여기에 기간 조건을 한 줄이라도 적으면 **반열린 구간
 *   규칙이 한 벌 더** 생기고, 「결재는 되는데 역할은 안 넘어오는」(또는 그 반대의)
 *   짝이 아무 오류 없이 생긴다.
 *   🔵 **역할을 못 찾은 위임자는 애초에 목록에 없다** — 이 집에 로그인한 적 없거나
 *   계정이 꺼진 사람이 그렇다(읽는 쪽 머리말). 그래서 여기서 「모름」을 다루지
 *   않고, 빈 목록은 「대신하는 사람이 없다」와 같은 뜻으로 읽힌다.
 *
 * ── 🔴 진짜 관리자는 **좁아지지 않는다** ───────────────────────────────
 * 자격이 둘이면 **높은 쪽이 이긴다.** 진짜 관리자가 누군가의 대리인이기도 할 때
 * `delegatedAdmin` 을 `true` 로 적으면, 그 사람은 **위임을 받았다는 이유만으로**
 * 역할 변경을 잃는다. 그래서 **먼저 제 역할을 보고 끝낸다.**
 *
 * ── 🔵 승격은 **한 겹**이다 ────────────────────────────────────────────
 * 임시 관리자가 또 누군가에게 맡겨도 그 사람은 관리자가 되지 못한다 — 읽는 질의가
 * `delegate_employee_id = 나` 한 줄만 보고 이어 붙지 않기 때문이고(위 머리말의
 * 읽는 쪽), 여기서도 되풀이하지 않는다.
 */
export function decideDelegatedAdmin(
  ownRole: UserRole,
  delegatorRoles: readonly UserRole[],
): DelegatedAdminDecision {
  // 🔴 진짜 관리자는 더 얻을 것도, 잃을 것도 없다(위 머리말).
  if (ownRole === DELEGATED_ADMIN_SOURCE_ROLE) return { isAdmin: true, delegatedAdmin: false };
  if (!delegatorRoles.includes(DELEGATED_ADMIN_SOURCE_ROLE)) {
    return { isAdmin: false, delegatedAdmin: false };
  }
  return { isAdmin: true, delegatedAdmin: true };
}

/**
 * **위임자들의 역할을 읽어 볼 까닭이 있나** — 질의 한 번을 아끼는 자리다.
 *
 * 🔴 **진짜 관리자에게는 묻지 않는다.** 얻을 것이 없고(위 판정이 첫 줄에서
 * 끝난다), 모든 화면이 지나는 길에 왕복을 하나 더 다는 것은 그 자체가 값이다.
 * 🔴 **대신하는 사람이 없어도 묻지 않는다.** 이 집의 사람 대부분이 그 쪽이다.
 *
 * 🔵 판정과 **같은 파일에** 둔 까닭: 「안 묻는다」가 곧 「`delegatorRoles` 가
 *    빈 목록이다」라서, 두 함수가 갈라지면 「물어봐야 하는데 안 물어 역할이 안
 *    넘어오는」 사람이 생긴다. 어느 쪽이든 결론은 위 `decideDelegatedAdmin` 하나를
 *    지나야 한다(부르는 쪽 `auth/guards.ts` 가 그렇게 적혀 있다).
 */
export function needsDelegatorRoles(
  ownRole: UserRole,
  actingForEmployeeIds: readonly string[],
): boolean {
  return ownRole !== DELEGATED_ADMIN_SOURCE_ROLE && actingForEmployeeIds.length > 0;
}

/**
 * 🔴 **막힌 사람이 보는 글.** 「권한이 없습니다」로 끝내면 임시 관리자는 **자기가
 * 왜 그것만 못 하는지** 모른다 — 다른 관리자 화면은 전부 열려 있기 때문이다.
 * 그래서 셋을 함께 적는다: **무엇이 막았나**(위임으로 받은 자격) · **왜**(바꾼
 * 역할은 기간이 끝나도 남는다) · **어떻게 하나**(휴가 관리자에게 요청).
 *
 * 🔵 **기간도 위임자 이름도 싣지 않는다** — 그 값을 실으려면 남의 위임 줄을 읽어야
 *    하고, 기간은 이미 [휴가 설정 → 결재권 위임]의 「내가 대신하고 있는 것」에 줄마다
 *    적혀 있다(머리말의 「임시」 배지가 그리로 보낸다).
 */
export const SET_ROLE_DELEGATED_ADMIN_MESSAGE =
  "결재권 위임으로 받은 임시 휴가 관리자 자격으로는 역할을 바꿀 수 없습니다. " +
  "여기서 지정한 휴가 관리자는 위임 기간이 끝난 뒤에도 그대로 남기 때문입니다. " +
  "역할을 바꿔야 하면 휴가 관리자에게 요청하십시오.";

/**
 * 🔴 **계정의 역할을 바꿀 수 있나** — 임시 관리자에게 주지 않는 **단 하나의 문**.
 *
 * ── 🔴 왜 이것 하나인가 ────────────────────────────────────────────────
 * `setRoleAction`(app/actions/admin.ts)은 아무 계정이나 `MEMBER` ↔ `LEAVE_ADMIN`
 * 으로 **즉시** 바꾼다. 안전장치는 「마지막 관리자는 못 뺀다」 하나뿐이고 **새
 * 관리자를 만드는 쪽은 아무것도 막지 않는다.** 그래서 이 문이 열려 있으면 임시
 * 관리자가 **영구 관리자를 찍어 낼 수 있고**(자기 자신을 포함해서), 위임 기간이
 * 끝나도 그 역할은 그대로 남는다 — 「기간 동안만」이라는 말 자체가 무너진다.
 *
 * 🔴 **나머지 관리자 문은 일부러 안 막았다**(2026-11-17 사용자 결정). 이 집의
 * 관리자 문 가운데 **대부분이** 기간이 끝나도 되돌아가지 않는다(연차 직접 조정 ·
 * 근속 표 · 공휴일 · 직원 명단 · 전사 여름휴가 일수 · **결재선 구성**). 쓰는 분이
 * 그것을 알고 **「역할 변경만 빼고 전부」**를 골랐다. 🔴 **여기에 조건을 더
 * 끼워 넣지 마라** — 늘리는 것은 결정을 바꾸는 일이다.
 *
 * 🔴 **화면 분기가 아니다.** 서버 액션이 이것을 물어 거절한다 — 그 액션은 네트워크
 * 경계 너머에서 불리고, 단추를 안 그리는 것은 울타리가 아니다(guards.ts 머리말).
 * 🔴 **문(`requireAdmin`)으로 막지 않는다.** 그쪽은 홈으로 튕기므로 막힌 사람이
 * **까닭을 볼 자리가 없고**, 화면을 열어 읽는 것까지 막혀 「지금 누가 관리자인가」
 * 조차 못 본다. 거절 문구는 폼이 그 자리에 그대로 그린다(ActionForm).
 *
 * 🔵 **칸 두 개를 묶어 받는다.** 참/거짓 둘을 나란히 받으면 부르는 쪽에서 **바꿔
 *    꽂아도 tsc 가 침묵한다** — `canOpenApprovalBox` 가 같은 까닭으로 같은 모양이다.
 *    `Viewer` 가 이 모양에 그대로 들어맞으므로 부르는 쪽은 그냥 넘기면 된다.
 */
export function mayChangeUserRole(actor: DelegatedAdminDecision): boolean {
  return actor.isAdmin && !actor.delegatedAdmin;
}
